CREATE TABLE IF NOT EXISTS customers (
    id UUID PRIMARY KEY,
    telegram_id BIGINT NOT NULL UNIQUE,
    display_name VARCHAR(256) NOT NULL,
    campaign VARCHAR(64),
    consent_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
COMMENT ON COLUMN customers.id IS 'Internal customer UUID, independent of Telegram identity';
COMMENT ON COLUMN customers.telegram_id IS 'Telegram user ID; private chat ID for notifications';
COMMENT ON COLUMN customers.display_name IS 'Name reported by Telegram; not a verified legal identity';
COMMENT ON COLUMN customers.campaign IS 'First valid start parameter; not a count of QR scans';
COMMENT ON COLUMN customers.consent_at IS 'UTC time when the customer accepted published terms';
COMMENT ON COLUMN customers.created_at IS 'UTC first interaction time';

CREATE TABLE IF NOT EXISTS model_files (
    id UUID PRIMARY KEY,
    customer_id UUID NOT NULL REFERENCES customers(id),
    telegram_file_id TEXT NOT NULL,
    original_name VARCHAR(255) NOT NULL,
    sha256 VARCHAR(64) NOT NULL,
    storage_name VARCHAR(80) NOT NULL,
    size_bytes BIGINT NOT NULL CHECK (size_bytes > 0)
);
COMMENT ON COLUMN model_files.id IS 'Internal model identifier';
COMMENT ON COLUMN model_files.customer_id IS 'Owner of the file';
COMMENT ON COLUMN model_files.telegram_file_id IS 'Telegram file ID for private operator delivery';
COMMENT ON COLUMN model_files.original_name IS 'Sanitized display name, never used as a path';
COMMENT ON COLUMN model_files.sha256 IS 'SHA-256 of validated file bytes';
COMMENT ON COLUMN model_files.storage_name IS 'Content-addressed local filename, relative to model storage';
COMMENT ON COLUMN model_files.size_bytes IS 'Validated file size in bytes';

CREATE TABLE IF NOT EXISTS orders (
    id UUID PRIMARY KEY,
    number BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE NOT NULL,
    customer_id UUID NOT NULL REFERENCES customers(id),
    status VARCHAR(32) NOT NULL,
    model_id UUID REFERENCES model_files(id),
    material_id VARCHAR(64),
    print_profile VARCHAR(32) NOT NULL DEFAULT 'STANDARD',
    infill INTEGER NOT NULL DEFAULT 15 CHECK (infill IN (15, 30, 60)),
    quantity INTEGER NOT NULL DEFAULT 1 CHECK (quantity BETWEEN 1 AND 100),
    promo_code VARCHAR(20) NOT NULL DEFAULT '',
    quote_id UUID,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    paid_at TIMESTAMP WITH TIME ZONE
);
COMMENT ON COLUMN orders.id IS 'Internal order identifier';
COMMENT ON COLUMN orders.number IS 'Human-readable number used in bot commands';
COMMENT ON COLUMN orders.customer_id IS 'Ordering Telegram user';
COMMENT ON COLUMN orders.status IS 'Application-validated lifecycle status';
COMMENT ON COLUMN orders.model_id IS 'Validated STL file selected for this batch';
COMMENT ON COLUMN orders.material_id IS 'Material and color key in configured catalog';
COMMENT ON COLUMN orders.print_profile IS 'STANDARD 0.20 mm or FINE 0.12 mm; checked by operator';
COMMENT ON COLUMN orders.infill IS 'Requested infill percentage';
COMMENT ON COLUMN orders.quantity IS 'Number of items; slicing estimates are already for this entire batch';
COMMENT ON COLUMN orders.promo_code IS 'Requested promotion; empty means no promotion';
COMMENT ON COLUMN orders.quote_id IS 'Current immutable quote; prior quotes remain in history';
COMMENT ON COLUMN orders.created_at IS 'UTC order creation time';
COMMENT ON COLUMN orders.paid_at IS 'UTC confirmed payment time; retained after refunds';
CREATE INDEX IF NOT EXISTS orders_customer_idx ON orders(customer_id, created_at);

CREATE TABLE IF NOT EXISTS quotes (
    id UUID PRIMARY KEY,
    order_id UUID NOT NULL REFERENCES orders(id),
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    snapshot TEXT NOT NULL,
    total NUMERIC(18, 2) NOT NULL,
    discount NUMERIC(18, 2) NOT NULL,
    contribution NUMERIC(18, 2) NOT NULL,
    approved_by UUID REFERENCES customers(id),
    approval_reason TEXT
);
COMMENT ON COLUMN quotes.id IS 'Unique quote version; old buttons cannot accept a new quote';
COMMENT ON COLUMN quotes.order_id IS 'Order being priced';
COMMENT ON COLUMN quotes.expires_at IS 'UTC exclusive expiration and promotion reservation deadline';
COMMENT ON COLUMN quotes.snapshot IS 'Immutable JSON of rates, estimate, costs, promotion and public price';
COMMENT ON COLUMN quotes.total IS 'Customer payment including delivery, RUB';
COMMENT ON COLUMN quotes.discount IS 'Discount on printing only, RUB';
COMMENT ON COLUMN quotes.contribution IS 'Planned contribution after variable costs, before fixed overhead, RUB';
COMMENT ON COLUMN quotes.approved_by IS 'Administrator authorizing a quote below the contribution threshold';
COMMENT ON COLUMN quotes.approval_reason IS 'Required reason for manual financial approval';

CREATE TABLE IF NOT EXISTS business_lock (id INTEGER PRIMARY KEY);
COMMENT ON COLUMN business_lock.id IS 'Singleton row lock serializing quota, order and payment changes';
INSERT INTO business_lock(id) VALUES (1);

CREATE TABLE IF NOT EXISTS promotion_reservations (
    order_id UUID PRIMARY KEY REFERENCES orders(id),
    customer_id UUID NOT NULL REFERENCES customers(id),
    code VARCHAR(20) NOT NULL,
    discount NUMERIC(18, 2) NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    redeemed BOOLEAN NOT NULL DEFAULT FALSE,
    UNIQUE(customer_id, code)
);
COMMENT ON COLUMN promotion_reservations.order_id IS 'Order holding or consuming the promotion';
COMMENT ON COLUMN promotion_reservations.customer_id IS 'Customer; one reservation or redemption per promotion';
COMMENT ON COLUMN promotion_reservations.code IS 'Promotion identity; changing terms must not reset usage';
COMMENT ON COLUMN promotion_reservations.discount IS 'Reserved discount budget in RUB';
COMMENT ON COLUMN promotion_reservations.expires_at IS 'UTC reservation deadline; redeemed rows do not expire';
COMMENT ON COLUMN promotion_reservations.redeemed IS 'True only after payment; refunds do not restore promotion eligibility';

CREATE TABLE IF NOT EXISTS payments (
    order_id UUID PRIMARY KEY REFERENCES orders(id),
    reference VARCHAR(128) NOT NULL UNIQUE,
    amount NUMERIC(18, 2) NOT NULL,
    confirmed_by UUID NOT NULL REFERENCES customers(id),
    confirmed_at TIMESTAMP WITH TIME ZONE NOT NULL,
    refund_reference VARCHAR(128) UNIQUE,
    refunded_at TIMESTAMP WITH TIME ZONE
);
COMMENT ON COLUMN payments.order_id IS 'Order paid once; duplicate confirmation is idempotent';
COMMENT ON COLUMN payments.reference IS 'Unique external transfer reference, entered by the operator';
COMMENT ON COLUMN payments.amount IS 'Amount actually received, RUB; must match the accepted quote';
COMMENT ON COLUMN payments.confirmed_by IS 'Administrator who verified receipt of funds';
COMMENT ON COLUMN payments.confirmed_at IS 'UTC manual payment confirmation time';
COMMENT ON COLUMN payments.refund_reference IS 'External reference of a full refund performed outside the bot';
COMMENT ON COLUMN payments.refunded_at IS 'UTC full refund confirmation time';

CREATE TABLE IF NOT EXISTS order_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id UUID NOT NULL REFERENCES orders(id),
    actor_id UUID REFERENCES customers(id),
    action VARCHAR(64) NOT NULL,
    detail TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
COMMENT ON COLUMN order_events.id IS 'Append-only audit sequence';
COMMENT ON COLUMN order_events.order_id IS 'Order affected by the action';
COMMENT ON COLUMN order_events.actor_id IS 'Internal actor UUID; null is a system event';
COMMENT ON COLUMN order_events.action IS 'Action or resulting status';
COMMENT ON COLUMN order_events.detail IS 'Audit reason or summary without payment credentials';
COMMENT ON COLUMN order_events.created_at IS 'UTC audit time';

CREATE TABLE IF NOT EXISTS order_actuals (
    order_id UUID PRIMARY KEY REFERENCES orders(id),
    snapshot TEXT NOT NULL,
    total_cost NUMERIC(18, 2) NOT NULL,
    contribution NUMERIC(18, 2) NOT NULL,
    recorded_at TIMESTAMP WITH TIME ZONE NOT NULL
);
COMMENT ON COLUMN order_actuals.order_id IS 'Order whose actual consumption was measured';
COMMENT ON COLUMN order_actuals.snapshot IS 'Actual total consumption including failed prints, using saved rates';
COMMENT ON COLUMN order_actuals.total_cost IS 'Actual-consumption cost estimate plus additional costs, RUB';
COMMENT ON COLUMN order_actuals.contribution IS 'Contribution at saved rates, not accounting net profit, RUB';
COMMENT ON COLUMN order_actuals.recorded_at IS 'UTC last correction time; corrections are audited';

CREATE TABLE IF NOT EXISTS bot_cursor (id INTEGER PRIMARY KEY, next_update BIGINT NOT NULL);
COMMENT ON COLUMN bot_cursor.id IS 'Singleton durable Telegram cursor';
COMMENT ON COLUMN bot_cursor.next_update IS 'Next getUpdates offset; committed with domain changes and outbox';
INSERT INTO bot_cursor(id, next_update) VALUES (1, 0);

CREATE TABLE IF NOT EXISTS outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    method VARCHAR(32) NOT NULL,
    payload TEXT NOT NULL,
    attempts INTEGER NOT NULL DEFAULT 0,
    next_attempt TIMESTAMP WITH TIME ZONE NOT NULL,
    delivered BOOLEAN NOT NULL DEFAULT FALSE,
    failed BOOLEAN NOT NULL DEFAULT FALSE
);
COMMENT ON COLUMN outbox.id IS 'Durable outgoing Telegram operation ID';
COMMENT ON COLUMN outbox.method IS 'Allowed Telegram API method';
COMMENT ON COLUMN outbox.payload IS 'JSON API arguments, never includes the bot token';
COMMENT ON COLUMN outbox.attempts IS 'Number of failed attempts';
COMMENT ON COLUMN outbox.next_attempt IS 'UTC earliest retry time';
COMMENT ON COLUMN outbox.delivered IS 'Telegram acknowledged this operation';
COMMENT ON COLUMN outbox.failed IS 'Permanent error or exhausted retries; inspect with admin queue command';
CREATE INDEX IF NOT EXISTS outbox_pending_idx ON outbox(delivered, failed, next_attempt);

CREATE TABLE IF NOT EXISTS slicing_jobs (
    id UUID PRIMARY KEY,
    order_id UUID NOT NULL REFERENCES orders(id),
    state VARCHAR(16) NOT NULL,
    attempts INTEGER NOT NULL DEFAULT 0,
    lease_until TIMESTAMP WITH TIME ZONE,
    result TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
COMMENT ON COLUMN slicing_jobs.id IS 'Durable slicing job UUID and artifact folder key';
COMMENT ON COLUMN slicing_jobs.order_id IS 'Order whose frozen parameters are sliced';
COMMENT ON COLUMN slicing_jobs.state IS 'QUEUED, RUNNING, DONE, FAILED or CANCELLED';
COMMENT ON COLUMN slicing_jobs.attempts IS 'Attempts including recovery after worker restart';
COMMENT ON COLUMN slicing_jobs.lease_until IS 'UTC worker lease; expired work may be retried';
COMMENT ON COLUMN slicing_jobs.result IS 'Estimate with preset hashes or a safe failure reason';
COMMENT ON COLUMN slicing_jobs.created_at IS 'UTC enqueue time';
